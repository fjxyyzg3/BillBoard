export function getValidationMessage(
  message: string | undefined,
  locale: Locale,
  kind: ActionErrorKind,
) {
  const actionMessages = messages[locale].actions;
  if (message?.startsWith("ENCRYPTION_")) return getEncryptionMessages(locale).failed;
  if (message === "Ledger is unavailable") return messages[locale].common.ledgerUnavailable;
  if (message === "Entry context is required; refresh and select a ledger") return messages[locale].ledgers.refreshRequired;

  if (!message) {
    return kind === "delete"
      ? actionMessages.couldNotDelete
      : kind === "update"
        ? actionMessages.couldNotUpdate
        : actionMessages.couldNotSave;
  }

  if (locale === "zh-CN") {
    const validationMessages = actionMessages.validation as Partial<Record<string, string>>;

    return validationMessages[message] ?? message;
  }

  return message;
}
